export const getProvincesForRegion = (regionName: string): string[] => {
  const found = MOROCCO_REGIONS.find((r) => r.region === regionName);
  if (!found) return ['إقليم شيشاوة'];
  return Object.keys(found.provinces);
};

export const getCommunesForProvince = (regionName: string, provinceName: string): string[] => {
  const foundRegion = MOROCCO_REGIONS.find((r) => r.region === regionName);
  if (!foundRegion) {
    // Fallback search across all regions if regionName isn't matched
    for (const r of MOROCCO_REGIONS) {
      if (r.provinces[provinceName]) {
        return r.provinces[provinceName];
      }
    }
    return ['شيشاوة', 'إمنتانوت', 'سيدي المختار', 'مجاط', 'مزوضة'];
  }
  return foundRegion.provinces[provinceName] || ['شيشاوة', 'إمنتانوت', 'سيدي المختار'];
};
